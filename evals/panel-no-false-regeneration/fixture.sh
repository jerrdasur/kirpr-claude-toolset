#!/usr/bin/env bash
# Package with //go:generate stringer: only a method body changes, the
# generator's input (type Status and its constants) does not.
set -euo pipefail
# Self-contained on purpose: fail fast when git would be the macOS xcrun shim,
# which cannot run inside the eval sandbox (its cache lives outside it).
git_path="$(command -v git || true)"
[ -n "$git_path" ] || { echo "fixture: git не найден в PATH" >&2; exit 1; }
if [ "$(uname -s)" = "Darwin" ] && { [ "$git_path" = /usr/bin/git ] || git --version | grep -q Apple; }; then
    echo "fixture: нужен git из Homebrew первым в PATH, не xcrun-шим (сейчас: $git_path)" >&2
    exit 1
fi
g() { git -c user.name=eval -c user.email=eval@example.invalid "$@"; }
g init -q -b main
mkdir -p pkg/rpc
printf 'module ordersrv\n\ngo 1.24\n' > go.mod

cat > pkg/rpc/status.go <<'EOF'
package rpc

//go:generate stringer -type=Status

type Status int

const (
	StatusNew Status = iota
	StatusPaid
)
EOF

cat > pkg/rpc/status_string.go <<'EOF'
// Code generated by "stringer -type=Status"; DO NOT EDIT.

package rpc

import "strconv"

const _Status_name = "StatusNewStatusPaid"

var _Status_index = [...]uint8{0, 9, 19}

func (i Status) String() string {
	if i < 0 || i >= Status(len(_Status_index)-1) {
		return "Status(" + strconv.FormatInt(int64(i), 10) + ")"
	}
	return _Status_name[_Status_index[i]:_Status_index[i+1]]
}
EOF

cat > pkg/rpc/total.go <<'EOF'
package rpc

import "fmt"

// FormatTotal renders an amount in kopecks as rubles.
func FormatTotal(kopecks int64) string {
	return fmt.Sprintf("%d.%d ₽", kopecks/100, kopecks%100)
}
EOF
g add . && g commit -q -m "PLF-1 base"

cat > pkg/rpc/total.go <<'EOF'
package rpc

import "fmt"

// FormatTotal renders an amount in kopecks as rubles with two decimals.
func FormatTotal(kopecks int64) string {
	return fmt.Sprintf("%d.%02d ₽", kopecks/100, kopecks%100)
}
EOF
