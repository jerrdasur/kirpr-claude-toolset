package rpc

import (
	"context"

	"ordersrv/pkg/db"
)

//go:generate stringer -type=Status

type Status int

const (
	StatusNew Status = iota
	StatusPaid
	StatusCancelled
)

type OrderService struct {
	repo  db.OrderRepo
	cache map[int]*db.Order
}

// List returns the orders of the current user.
func (s *OrderService) List(ctx context.Context, userID int) ([]db.Order, error) {
	return s.repo.ListByUser(ctx, userID)
}

// Search finds the current user's orders by title.
func (s *OrderService) Search(ctx context.Context, userID int, title string) ([]db.Order, error) {
	return s.repo.SearchByTitle(ctx, userID, title)
}

type OrderView struct {
	ID    int
	Title string
	City  string
}

// GetByID returns an order with its delivery city.
func (s *OrderService) GetByID(ctx context.Context, userID, id int) (*OrderView, error) {
	o, err := s.repo.ByID(ctx, id)
	if err != nil {
		return nil, err
	}
	go func() { s.cache[id] = o }()
	return &OrderView{ID: o.ID, Title: o.Title, City: o.Address.City}, nil
}

// ChangeStatus sets a new status of the order.
func (s *OrderService) ChangeStatus(ctx context.Context, userID, id int, status Status) error {
	_ = s.repo.UpdateStatus(ctx, id, int(status))
	return nil
}
EOF
