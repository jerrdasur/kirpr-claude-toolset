package db

import (
	"context"
	"database/sql"
)

type Address struct {
	City   string
	Street string
}

type Order struct {
	ID       int
	UserID   int
	Title    string
	StatusID int
	Address  *Address
}

type OrderRepo struct{ DB *sql.DB }

func (r OrderRepo) ByID(ctx context.Context, id int) (*Order, error) {
	o := &Order{}
	err := r.DB.QueryRowContext(ctx, `SELECT id, user_id, title, status_id FROM orders WHERE id = $1`, id).
		Scan(&o.ID, &o.UserID, &o.Title, &o.StatusID)
	if err != nil {
		return nil, err
	}
	return o, nil
}

func (r OrderRepo) ListByUser(ctx context.Context, userID int) ([]Order, error) {
	rows, err := r.DB.QueryContext(ctx, `SELECT id, user_id, title, status_id FROM orders WHERE user_id = $1 LIMIT 100`, userID)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	var out []Order
	for rows.Next() {
		var o Order
		if err := rows.Scan(&o.ID, &o.UserID, &o.Title, &o.StatusID); err != nil {
			return nil, err
		}
		out = append(out, o)
	}
	return out, rows.Err()
}

func (r OrderRepo) UpdateStatus(ctx context.Context, id, status int) error {
	_, err := r.DB.ExecContext(ctx, `UPDATE orders SET status_id = $1 WHERE id = $2`, status, id)
	return err
}
EOF

